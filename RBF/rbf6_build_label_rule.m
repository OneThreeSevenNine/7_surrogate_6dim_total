function rule = rbf6_build_label_rule(X,Y,c)
% Calibrate a frozen speed-dependent flow envelope from trusted reference rows.
validateattributes(X,{'double'},{'real','finite','2d','ncols',3});
validateattributes(Y,{'double'},{'real','2d','ncols',6,'nrows',size(X,1)});
if size(X,1)<c.label_reference_rows
    error('RBF6:LabelReference','Need at least %d training rows',c.label_reference_rows);
end
ids=(1:c.label_reference_rows)';
reference=Y(ids,:);
trusted=all(isfinite(reference),2) & reference(:,1)>0 & reference(:,4)>0 & ...
    reference(:,2)>c.efficiency_bounds(1) & reference(:,2)<c.efficiency_bounds(2) & ...
    reference(:,5)>c.efficiency_bounds(1) & reference(:,5)<c.efficiency_bounds(2) & ...
    reference(:,3)>c.pressure_ratio_min & reference(:,6)>c.pressure_ratio_min;
if sum(trusted)~=c.label_reference_usable_count
    error('RBF6:LabelReference','Expected %d usable reference rows, got %d', ...
        c.label_reference_usable_count,sum(trusted));
end
mins=zeros(numel(c.speed_nodes),2); maxs=mins;
for k=1:numel(c.speed_nodes)
    take=trusted==1 & X(ids,1)==c.speed_nodes(k);
    if ~any(take), error('RBF6:LabelReference','No usable reference rows at Nf=%g',c.speed_nodes(k)); end
    flows=Y(ids(take),[1 4]); mins(k,:)=min(flows,[],1); maxs(k,:)=max(flows,[],1);
end
margin=c.label_margin_fraction*(maxs-mins);
rule=struct('version',3,'kind','speed_flow_envelope', ...
    'speed_nodes',c.speed_nodes(:)', ...
    'wb_reference_min',mins(:,1)','wb_reference_max',maxs(:,1)', ...
    'wc_reference_min',mins(:,2)','wc_reference_max',maxs(:,2)', ...
    'wb_lower',(mins(:,1)-margin(:,1))','wb_upper',(maxs(:,1)+margin(:,1))', ...
    'wc_lower',(mins(:,2)-margin(:,2))','wc_upper',(maxs(:,2)+margin(:,2))', ...
    'margin_fraction',c.label_margin_fraction,'reference_rows',c.label_reference_rows, ...
    'reference_usable_count',sum(trusted),'efficiency_bounds',c.efficiency_bounds, ...
    'pressure_ratio_min',c.pressure_ratio_min,'description',c.label_rule);
end
